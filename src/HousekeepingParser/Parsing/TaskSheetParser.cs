using System.Globalization;
using System.Text.RegularExpressions;
using HousekeepingParser.Core;

namespace HousekeepingParser.Parsing;

/// <summary>
/// Reads an Opera "Task Sheet Report" from positioned lines (plan 9.3). Rows are found by the room
/// number at the left edge; every other word is put into a column by its x position. Staff names and
/// staff numbers are never read into the result (rule 3): the attendant lines are skipped and the
/// instruction text goes through <see cref="NameFilter"/>.
/// </summary>
public static partial class TaskSheetParser
{
    // Column boundaries in points from the left page edge (Oracle Reports layout "hsk_tasksheet_11").
    // Header positions: Room No 15, Room Status 40, Credits (right-aligned) …92, Resv Status 96,
    // Arrival 138, Departure 177, Adl 219–236, Chl 240, Tasks 265.
    private static readonly (string Name, double From, double To)[] Columns =
    [
        ("marker", 0, 10),
        ("room", 10, 38),
        ("status", 38, 65),
        ("credits", 65, 94.5),
        ("resv", 94.5, 135),
        ("arrival", 135, 173),
        ("departure", 173, 214),
        ("adults", 214, 239),
        ("children", 239, 260),
        ("tasks", 260, double.MaxValue),
    ];

    private static readonly string[] SummaryLabels =
        ["Total Task Sheets", "Total Rooms", "Departure Rooms", "Dirty Rooms", "Clean Rooms", "Total Credits"];

    public static TaskSheetReport Parse(IReadOnlyList<PdfPage> pages)
    {
        var warnings = new List<ParseWarning>();
        var header = ParseHeader(pages, out var isTaskSheetReport);
        var sheets = new List<SheetBuilder>();
        var rooms = new List<ParsedRoom>();
        var invalidDataPages = new List<int>();
        ReportSummary? summary = null;

        // Names printed on attendant lines of this file: a safety net for the instruction filter.
        var knownNames = CollectAttendantNames(pages);

        foreach (var page in pages)
        {
            var lines = page.Lines;
            if (lines.Any(l => l.Text.Contains("Report Summary", StringComparison.Ordinal)))
            {
                summary = ParseSummary(lines, warnings);
                continue;
            }

            // The October sample starts with a room-number-only cover. Do not drop a real first data page.
            if (page.PageNumber == 1 && IsRoomNumberCover(page)) continue;

            var sheet = CurrentSheet(lines, page.PageNumber, sheets);
            var dataPage = sheet is not null || lines.Any(IsTableHeader) || HasRoomRows(page);
            if (dataPage && !HasLayoutSignature(page)) invalidDataPages.Add(page.PageNumber);
            if (sheet is null) continue;

            var inTable = false;
            foreach (var line in lines)
            {
                var text = line.Text;
                if (!inTable && IsTableHeader(line))
                {
                    inTable = true;
                    continue;
                }
                if (text.StartsWith("Total for Attendant", StringComparison.Ordinal) || text.StartsWith("@ Sleep", StringComparison.Ordinal))
                    inTable = false;

                if (inTable)
                {
                    var room = ParseRoomRow(line, sheet.SheetNo, page.PageNumber, warnings);
                    if (room is not null) rooms.Add(room);
                    continue;
                }

                if (text.StartsWith("Instructions", StringComparison.Ordinal))
                    sheet.Instructions = NameFilter.CleanInstructions(ValuesRightOf(line, 85), knownNames);
                else if (text.Contains("Generated", StringComparison.Ordinal))
                    sheet.AutoGenerated ??= line.Words.Select(w => w.Text).FirstOrDefault(t => t is "Y" or "N") switch
                    {
                        "Y" => true,
                        "N" => false,
                        _ => null,
                    };

                ReadSheetTotal(text, sheet);
            }
        }

        if (header?.HotelId is { } hotel)
        {
            foreach (var r in rooms.Where(r => !RoomInventory.Contains(hotel, r.RoomNo)))
                warnings.Add(new ParseWarning("UNKNOWN_ROOM", $"Room {r.RoomNo} is not in the {Hotels.ShortName(hotel)} room list."));
        }

        return new TaskSheetReport(
            isTaskSheetReport,
            header,
            sheets.Select(s => s.Build()).ToList(),
            rooms,
            summary,
            warnings) { InvalidDataPages = invalidDataPages };
    }

    internal static bool HasLayoutSignature(PdfPage page)
    {
        var text = string.Join(' ', page.Lines.Select(l => l.Text));
        var words = page.Lines.SelectMany(l => l.Words).ToList();
        bool Nearby(string first, string second, double x, double y) => words.Any(a => a.Text.Trim('.', ':').Equals(first, StringComparison.OrdinalIgnoreCase)
            && words.Any(b => b.Text.Trim('.', ':').Equals(second, StringComparison.OrdinalIgnoreCase)
                && Math.Abs(a.Left - b.Left) <= x && Math.Abs(a.CentreY - b.CentreY) <= y));
        // Opera wraps "Resv Status" over two header lines; adjacency in flattened page text is unreliable.
        return (Regex.IsMatch(text, @"\bRoom\s+Details\b", RegexOptions.IgnoreCase) || Nearby("Room", "Details", 45, 15))
            && (Regex.IsMatch(text, @"\bResv\s+Status\b", RegexOptions.IgnoreCase) || Nearby("Resv", "Status", 40, 18));
    }

    private static bool HasRoomRows(PdfPage page) => page.Lines.Any(l => l.Words.Any(w =>
        w.Left >= 10 && w.Left < 38 && RoomNumber().IsMatch(w.Text)));

    private static bool IsRoomNumberCover(PdfPage page)
    {
        var candidates = page.Lines.Select(l => ParseRoomRow(l, "", page.PageNumber, [])).Where(r => r is not null).ToList();
        return candidates.Count > 0 && candidates.All(r => r!.RoomStatus.Length == 0 && r.Credits is null
            && r.ReservationStatus.Length == 0 && r.Arrival is null && r.Departure is null);
    }

    // ---------- header ----------

    private static TaskSheetHeader? ParseHeader(IReadOnlyList<PdfPage> pages, out bool isTaskSheetReport)
    {
        isTaskSheetReport = false;
        var first = pages.FirstOrDefault(p => p.Lines.Count > 0);
        if (first is null) return null;

        // Opera prints the time slightly above the title. The .NET reader therefore returns
        // separate lines: recognise the header by position without widening room-row grouping.
        var top = first.Lines.Take(8).Where(l => l.CentreY >= first.Height - 110).ToList();
        var title = top.FirstOrDefault(l => TitleLine().IsMatch(l.Text));
        if (title is null) return null;
        isTaskSheetReport = true;

        var hotelLine = top.Select(l => HotelLine().Match(l.Text)).FirstOrDefault(m => m.Success);
        if (hotelLine is null) return null;
        var date = ParseDate(hotelLine.Groups["date"].Value);
        if (date is null) return null;

        var timeText = TitleLine().Match(title.Text).Groups["time"].Value;
        if (timeText.Length == 0)
        {
            // Only accept one nearby, right-hand print time; never borrow a time from the room table.
            var candidates = top.SelectMany(l => l.Words)
                .Where(w => w.Left >= title.Right && Math.Abs(w.CentreY - title.CentreY) <= 12
                    && PrintTime().IsMatch(w.Text)).ToList();
            if (candidates.Count != 1) return null;
            timeText = candidates[0].Text;
        }
        if (!TimeOnly.TryParseExact(timeText, "HH:mm", CultureInfo.InvariantCulture, DateTimeStyles.None, out var time))
            return null;

        var printed = hotelLine.Groups["hotel"].Value.Trim();
        return new TaskSheetHeader(printed, Hotels.FromPrintedName(printed), date.Value, date.Value.ToDateTime(time));
    }

    // ---------- sheets ----------

    private sealed class SheetBuilder(string sheetNo, DateOnly? date, string codes, int firstPage)
    {
        public string SheetNo { get; } = sheetNo;
        public int FirstPage { get; } = firstPage;
        public int LastPage { get; set; }
        public string? Instructions { get; set; }
        public bool? AutoGenerated { get; set; }
        public int? Rooms, Departures, Adults, Children, Clean, Dirty;
        public decimal? Credits;
        public bool HasTotals;

        public ParsedSheet Build() => new(
            SheetNo,
            date,
            codes,
            AutoGenerated,
            string.IsNullOrWhiteSpace(Instructions) ? NameFilter.NoInstructions : Instructions,
            HasTotals ? new SheetTotals(Rooms, Departures, Adults, Children, Credits, Clean, Dirty) : null,
            FirstPage,
            Math.Max(FirstPage, LastPage));
    }

    private static SheetBuilder? CurrentSheet(IReadOnlyList<PdfLine> lines, int page, List<SheetBuilder> sheets)
    {
        foreach (var line in lines.Take(12))
        {
            var m = SheetLine().Match(line.Text);
            if (!m.Success) continue;
            var no = m.Groups["no"].Value;
            var last = sheets.LastOrDefault();
            if (last is not null && last.SheetNo == no)
            {
                last.LastPage = page; // a long sheet continues on the next page
                return last;
            }
            var sheet = new SheetBuilder(no, ParseDate(m.Groups["date"].Value), m.Groups["codes"].Value, page);
            sheets.Add(sheet);
            return sheet;
        }
        return null;
    }

    private static void ReadSheetTotal(string text, SheetBuilder sheet)
    {
        var m = SheetTotalLine().Match(text);
        if (!m.Success) return;
        sheet.HasTotals = true;
        var value = m.Groups["value"].Success ? m.Groups["value"].Value : null;
        switch (m.Groups["label"].Value)
        {
            case "Total Rooms": sheet.Rooms = ParseInt(value); break;
            case "Departure Rooms": sheet.Departures = ParseInt(value); break;
            case "Total Adults": sheet.Adults = ParseInt(value); break;
            case "Total Children": sheet.Children = ParseInt(value); break;
            case "Total Credits": sheet.Credits = ParseDecimal(value); break;
            case "Clean": sheet.Clean = ParseInt(value); break;
            case "Dirty": sheet.Dirty = ParseInt(value); break;
        }
    }

    // ---------- rooms ----------

    private static bool IsTableHeader(PdfLine line) =>
        line.Words.Count > 2
        && line.Words[0].Text == "Room"
        && line.Words[0].Left < 40
        && line.Words.Any(w => w.Text is "Tasks" or "Status" or "Credits");

    private static ParsedRoom? ParseRoomRow(PdfLine line, string sheetNo, int page, List<ParseWarning> warnings)
    {
        var cells = new Dictionary<string, List<PdfWord>>();
        foreach (var w in line.Words)
        {
            var col = ColumnAt(w.Left + 0.5);
            if (!cells.TryGetValue(col, out var list)) cells[col] = list = [];
            list.Add(w);
        }
        if (!cells.TryGetValue("room", out var roomWords) || roomWords.Count != 1 || !RoomNumber().IsMatch(roomWords[0].Text))
            return null;

        string Cell(string name) => cells.TryGetValue(name, out var ws) ? string.Join(' ', ws.Select(x => x.Text)) : "";

        var roomNo = roomWords[0].Text;
        var status = Cell("status");
        if (status.Length > 0 && !RoomStatus().IsMatch(status))
            warnings.Add(new ParseWarning("BAD_CELL", $"Room {roomNo}: room status '{status}' could not be read."));

        var credits = Cell("credits");
        var arrival = Cell("arrival");
        var departure = Cell("departure");
        var adults = Cell("adults");
        var children = Cell("children");
        var marker = Cell("marker");

        DateOnly? Date(string value, string what)
        {
            if (value.Length == 0) return null;
            var d = ParseDate(value);
            if (d is null) warnings.Add(new ParseWarning("BAD_CELL", $"Room {roomNo}: {what} '{value}' is not a date."));
            return d;
        }

        int? Count(string value, string what)
        {
            if (value.Length == 0) return null;
            var n = ParseInt(value);
            if (n is null) warnings.Add(new ParseWarning("BAD_CELL", $"Room {roomNo}: {what} '{value}' is not a number."));
            return n;
        }

        var word = roomWords[0];
        var adultCount = Count(adults, "adults");
        // Opera omits Chl when there are no children; do not turn a wholly incomplete row into a valid zero.
        var childCount = children.Length == 0 && adultCount is not null && (arrival.Length > 0 || departure.Length > 0)
            ? 0 : Count(children, "children");
        // Task codes are reference data only; normalize the known export typo without driving colours from it.
        var tasks = Regex.Replace(Cell("tasks"), @"\bGLCL\b", "GLC", RegexOptions.IgnoreCase);
        return new ParsedRoom(
            roomNo,
            sheetNo,
            status,
            credits.Length > 0 ? ParseDecimal(credits) : null,
            Cell("resv"),
            Date(arrival, "arrival"),
            Date(departure, "departure"),
            adultCount,
            childCount,
            tasks,
            marker is "!" or "@" or "#" ? marker : null,
            new RoomPosition(page, word.Left, word.Top, word.Bottom));
    }

    private static string ColumnAt(double x)
    {
        foreach (var (name, from, to) in Columns)
        {
            if (x >= from && x < to) return name;
        }
        return "tasks";
    }

    // ---------- summary ----------

    private static ReportSummary? ParseSummary(IReadOnlyList<PdfLine> lines, List<ParseWarning> warnings)
    {
        var values = new Dictionary<string, string>();
        foreach (var line in lines)
        {
            foreach (var label in SummaryLabels)
            {
                var m = Regex.Match(line.Text, $@"^{Regex.Escape(label)}\s+(?<v>\d+(?:[.,]\d+)?)$");
                if (m.Success) values[label] = m.Groups["v"].Value;
            }
        }

        var missing = SummaryLabels.Where(l => !values.ContainsKey(l)).ToList();
        if (missing.Count > 0)
        {
            warnings.Add(new ParseWarning("SUMMARY_INCOMPLETE", $"Report Summary is missing: {string.Join(", ", missing)}."));
            return null;
        }

        int I(string label) => ParseInt(values[label]) ?? throw new FormatException(label);
        var credits = ParseDecimal(values["Total Credits"]);
        try
        {
            return credits is null
                ? null
                : new ReportSummary(I("Total Task Sheets"), I("Total Rooms"), I("Departure Rooms"), I("Dirty Rooms"), I("Clean Rooms"), credits.Value);
        }
        catch (FormatException ex)
        {
            warnings.Add(new ParseWarning("SUMMARY_INCOMPLETE", $"Report Summary value '{ex.Message}' is not a number."));
            return null;
        }
    }

    // ---------- names (read only to filter them out, never returned) ----------

    private static HashSet<string> CollectAttendantNames(IReadOnlyList<PdfPage> pages)
    {
        var names = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var line in pages.SelectMany(p => p.Lines))
        {
            var t = line.Text;
            if (t.Contains("Attendant Id and Name", StringComparison.Ordinal)
                || t.StartsWith("Attendant Instructions", StringComparison.Ordinal)
                || t.StartsWith("Total for Attendant", StringComparison.Ordinal))
            {
                foreach (var w in line.Words.Where(w => w.Left > 85))
                    names.Add(w.Text.Trim('.', ',', '/', '-'));
            }
        }
        names.RemoveWhere(n => n.Length < 2);
        return names;
    }

    private static string ValuesRightOf(PdfLine line, double x) =>
        string.Join(' ', line.Words.Where(w => w.Left >= x).Select(w => w.Text));

    // ---------- values ----------

    internal static DateOnly? ParseDate(string s) =>
        DateOnly.TryParseExact(s.Trim(), "dd.MM.yy", CultureInfo.InvariantCulture, DateTimeStyles.None, out var d) ? d : null;

    private static int? ParseInt(string? s) =>
        int.TryParse(s, NumberStyles.None, CultureInfo.InvariantCulture, out var n) ? n : null;

    /// <summary>Credits use a German decimal comma ("250,5").</summary>
    private static decimal? ParseDecimal(string? s) =>
        s is not null && decimal.TryParse(s.Replace(',', '.'), NumberStyles.AllowDecimalPoint, CultureInfo.InvariantCulture, out var d) ? d : null;

    [GeneratedRegex(@"^(?<hotel>.+?)\s+(?<date>\d{2}\.\d{2}\.\d{2})$")]
    private static partial Regex HotelLine();

    [GeneratedRegex(@"^Task\s+Sheet\s+Report(?:\s+(?<time>\d{2}:\d{2}))?$")]
    private static partial Regex TitleLine();

    [GeneratedRegex(@"^\d{2}:\d{2}$")]
    private static partial Regex PrintTime();

    [GeneratedRegex(@"(?<date>\d{2}\.\d{2}\.\d{2})/(?<codes>[A-Z,]+)/(?<no>\d+|FLOAT)\b")]
    private static partial Regex SheetLine();

    [GeneratedRegex(@"^(?<label>Total Rooms|Departure Rooms|Total Adults|Total Children|Total Credits|Clean|Dirty)(?:\s+(?<value>\d+(?:,\d+)?))?$")]
    private static partial Regex SheetTotalLine();

    [GeneratedRegex(@"^\d{3,4}$")]
    private static partial Regex RoomNumber();

    [GeneratedRegex(@"^[A-Z]{2}$")]
    private static partial Regex RoomStatus();
}
