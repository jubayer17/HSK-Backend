using HousekeepingParser.Core;

namespace HousekeepingParser.Parsing;

public sealed record TaskSheetHeader(
    string PrintedHotelName,
    HotelId? HotelId,
    DateOnly ReportDate,
    /// <summary>Berlin local time printed in the header (date + HH:MM).</summary>
    DateTime PublishedAtLocal);

public sealed record SheetTotals(
    int? Rooms,
    int? DepartureRooms,
    int? Adults,
    int? Children,
    decimal? Credits,
    int? Clean,
    int? Dirty);

public sealed record ParsedSheet(
    /// <summary>Text, never a number: it can be "FLOAT".</summary>
    string SheetNo,
    DateOnly? SheetDate,
    string TaskCodes,
    bool? AutoGenerated,
    /// <summary>After the name filter. "Keine TA." when empty.</summary>
    string Instructions,
    SheetTotals? Totals,
    int FirstPage,
    int LastPage);

public sealed record RoomPosition(int Page, double Left, double Top, double Bottom);

public sealed record ParsedRoom(
    string RoomNo,
    string SheetNo,
    string RoomStatus,
    decimal? Credits,
    string ReservationStatus,
    DateOnly? Arrival,
    DateOnly? Departure,
    int? Adults,
    int? Children,
    string Tasks,
    /// <summary>"!" arrival, "@" sleep, "#" skip, or null.</summary>
    string? Marker,
    RoomPosition Position);

public sealed record ReportSummary(
    int TotalTaskSheets,
    int TotalRooms,
    int DepartureRooms,
    int DirtyRooms,
    int CleanRooms,
    decimal TotalCredits);

public sealed record ParseWarning(string Code, string Message);

public sealed record TaskSheetReport(
    bool IsTaskSheetReport,
    TaskSheetHeader? Header,
    IReadOnlyList<ParsedSheet> Sheets,
    IReadOnlyList<ParsedRoom> Rooms,
    ReportSummary? Summary,
    IReadOnlyList<ParseWarning> Warnings,
    /// <summary>Pages with room rows but without "Room Details" and the "Resv Status" column: not the known Opera layout.</summary>
    IReadOnlyList<int> PagesWithoutLayout);
